#!/usr/bin/env python3
"""Generate the fallback stub for every Windows function the .NET code calls,
and the Mono configuration that routes those calls to the stand-in library.

    gen_stubs.py <pinvokes.tsv> <stubs.c> <mono config> <library path>

Each stub is a weak symbol: a real implementation of the same name anywhere in
native/ replaces it at link time. A stub that does get called logs its name
once (so the log is the to-do list) and returns 0.

Names that libSystem already exports (rare) are emitted with a "wmcapi_"
prefix and mapped by name in the configuration, so the stand-in never
shadows a C library function it may itself need.
"""
import ctypes
import os
import sys

MONO_ENTRIES = """\
	<dllmap dll="libc" target="libc.dylib" os="!windows"/>
	<dllmap dll="MonoPosixHelper" target="$mono_libdir/libMonoPosixHelper.dylib" os="!windows" />
	<dllmap dll="System.Native" target="$mono_libdir/libmono-native.dylib" os="!windows" />
	<dllmap dll="System.Net.Security.Native" target="$mono_libdir/libmono-native.dylib" os="!windows" />
	<dllmap dll="System.Security.Cryptography.Native.Apple" target="$mono_libdir/libmono-native.dylib" os="osx" />
	<dllmap dll="libmono-btls-shared" target="$mono_libdir/libmono-btls-shared.dylib" os="!windows" />
	<dllmap dll="sqlite3" target="libsqlite3.0.dylib" os="!windows"/>
"""


def main():
    tsv, stubs_c, config, library = sys.argv[1:5]
    libsystem = ctypes.CDLL(None)

    def taken(name):
        try:
            getattr(libsystem, name)
            return True
        except AttributeError:
            return False

    modules = {}
    for line in open(tsv, encoding="utf-8"):
        cols = line.rstrip("\n").split("\t")
        module, entry = cols[0], cols[1]
        if module == "(self)":
            continue
        modules.setdefault(module, set()).add(entry)

    names = {}
    for module, entries in modules.items():
        for entry in entries:
            names.setdefault(entry, module)

    renamed = sorted(n for n in names if taken(n))
    with open(stubs_c, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_stubs.py. Do not edit. */\n")
        f.write("#include <stdint.h>\n")
        f.write("intptr_t wmc_stub_hit(const char *module, const char *name);\n")
        f.write("#define STUB(sym, module, name) \\\n")
        f.write("    __attribute__((weak, visibility(\"default\"))) intptr_t sym(void) \\\n")
        f.write("    { return wmc_stub_hit(module, name); }\n\n")
        for name in sorted(names, key=str.lower):
            sym = "wmcapi_" + name if name in renamed else name
            if not sym.replace("_", "a").isalnum():
                continue
            f.write('STUB(%s, "%s", "%s")\n' % (sym, names[name], name))

    with open(config, "w", encoding="utf-8") as f:
        f.write("<configuration>\n")
        f.write(MONO_ENTRIES)
        f.write('\t<dllmap dll="wmcshim" target="%s"/>\n' % library)
        # System.Drawing draws through Mono's GDI+ library (tools/setup_toolchain.py).
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        toolchain = os.environ.get("WMC_TOOLCHAIN") or os.path.join(root, "toolchain")
        gdiplus = os.path.join(toolchain, "libgdiplus", "lib", "libgdiplus.0.dylib")
        if os.path.exists(gdiplus):
            for name in ("gdiplus", "gdiplus.dll", "gdi32", "gdi32.dll"):
                if name.startswith("gdiplus"):
                    f.write('\t<dllmap dll="%s" target="%s"/>\n' % (name, gdiplus))
        for module in sorted(modules):
            variants = [module]
            base, ext = os.path.splitext(module)
            if ext == ".dll":
                variants.append(base)
            special = sorted(n for n in modules[module] if n in renamed)
            for v in variants:
                if special:
                    f.write('\t<dllmap dll="i:%s" target="%s">\n' % (v, library))
                    for n in special:
                        f.write('\t\t<dllentry dll="%s" name="%s" target="wmcapi_%s"/>\n'
                                % (library, n, n))
                    f.write("\t</dllmap>\n")
                else:
                    f.write('\t<dllmap dll="i:%s" target="%s"/>\n' % (v, library))
        f.write("</configuration>\n")

    print("%d stubs over %d modules; renamed: %s" % (
        len(names), len(modules), ", ".join(renamed) or "none"))


if __name__ == "__main__":
    main()
